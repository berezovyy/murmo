//! Path filter: skip env, secrets, lockfiles, vendored, generated (E16).

/// Bump when exclusion rules change; part of the names cache key.
pub const EXCLUSION_VERSION: u32 = 1;
pub const MAX_FILE_BYTES: u64 = 1024 * 1024;
pub const MAX_NAME_CHARS: usize = 180;

fn basename(path: &str) -> &str {
    path.rsplit('/').next().unwrap_or(path)
}

fn ext(name: &str) -> &str {
    match name.rfind('.') {
        Some(i) if i > 0 => &name[i..],
        _ => "",
    }
}

fn skip_dir(path: &str) -> bool {
    let lower = path.to_ascii_lowercase();
    for part in lower.split('/') {
        if matches!(
            part,
            "node_modules"
                | "vendor"
                | "vendored"
                | "third_party"
                | "third-party"
                | "target"
                | "dist"
                | "build"
                | "generated"
                | "__generated__"
                | ".git"
                | ".yarn"
                | ".cache"
                | "snapshots"
        ) {
            return true;
        }
    }
    false
}

fn is_lock(path: &str) -> bool {
    let name = basename(path);
    matches!(
        name,
        "package-lock.json"
            | "npm-shrinkwrap.json"
            | "pnpm-lock.yaml"
            | "bun.lockb"
            | "yarn.lock"
            | "Cargo.lock"
            | "poetry.lock"
            | "composer.lock"
            | "go.sum"
            | "Pipfile.lock"
            | "uv.lock"
    ) || name.ends_with("lock")
        || name.ends_with("lockfile")
}

fn is_secret_name(name: &str) -> bool {
    let lower = name.to_ascii_lowercase();
    matches!(ext(&lower), ".pem" | ".key" | ".p12" | ".pfx" | ".crt")
        || lower.starts_with("secret")
        || lower.starts_with("credential")
}

fn is_env(path: &str) -> bool {
    basename(path).starts_with(".env")
}

fn generated_name(path: &str) -> bool {
    let lower = path.to_ascii_lowercase();
    lower.contains(".generated.")
        || lower.contains(".gen.")
        || lower.contains(".pb.")
        || lower.contains("_generated.")
}

/// True when a tracked posix path may be read for names.
pub fn path_allowed(posix_path: &str) -> bool {
    if posix_path.is_empty() {
        return false;
    }
    if skip_dir(posix_path) || generated_name(posix_path) || is_env(posix_path) {
        return false;
    }
    if is_lock(posix_path) {
        return false;
    }
    if is_secret_name(basename(posix_path)) {
        return false;
    }
    true
}

pub fn is_source_ext(path: &str) -> bool {
    matches!(
        ext(basename(path)).to_ascii_lowercase().as_str(),
        ".rs"
            | ".ts"
            | ".tsx"
            | ".js"
            | ".jsx"
            | ".mjs"
            | ".cjs"
            | ".py"
            | ".go"
            | ".c"
            | ".h"
            | ".cpp"
            | ".hpp"
            | ".cc"
            | ".zig"
            | ".sh"
            | ".bash"
            | ".zsh"
            | ".rb"
            | ".java"
            | ".kt"
            | ".swift"
            | ".lua"
    )
}

/// Grammar id for a path, if a tree-sitter grammar is loaded for it.
pub fn grammar_of(path: &str) -> Option<&'static str> {
    match ext(basename(path)).to_ascii_lowercase().as_str() {
        ".rs" => Some("rust"),
        ".ts" => Some("typescript"),
        ".tsx" => Some("tsx"),
        ".js" | ".jsx" | ".mjs" | ".cjs" => Some("javascript"),
        ".py" => Some("python"),
        ".go" => Some("go"),
        _ => None,
    }
}

const GENERATED_HEADER: &[&str] = &[
    "automatically generated",
    "auto-generated",
    "@generated",
    "generated by",
    "generated from",
    "do not edit",
];

/// True when the file header says the contents are generated.
pub fn is_generated_header(text: &str) -> bool {
    let header = if text.len() > 4096 {
        &text[..4096]
    } else {
        text
    };
    let lower = header.to_ascii_lowercase();
    GENERATED_HEADER.iter().any(|p| lower.contains(p))
}

#[cfg(test)]
mod tests {
    use super::path_allowed;

    #[test]
    fn exclusions_drop_env_keys_locks_vendor() {
        assert!(!path_allowed(".env"));
        assert!(!path_allowed(".env.local"));
        assert!(!path_allowed("secrets.pem"));
        assert!(!path_allowed("credential.json"));
        assert!(!path_allowed("package-lock.json"));
        assert!(!path_allowed("Cargo.lock"));
        assert!(!path_allowed("vendor/lib.rs"));
        assert!(!path_allowed("node_modules/x/index.js"));
        assert!(!path_allowed("target/debug/foo.rs"));
        assert!(!path_allowed("src/foo.generated.rs"));
        assert!(
            path_allowed("src/keymap.rs"),
            "substring key must not drop keymap.rs"
        );
        assert!(path_allowed("src/outbox/worker.rs"));
    }
}

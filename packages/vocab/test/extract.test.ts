// Whole-identifier extraction, exclusions, manifests. Catches protecting
// fragments like `nd`/`fo` (r6 § 2) and reading `.env` (architecture rule).
import assert from 'node:assert/strict';
import { test } from 'node:test';
import {
  identifiersIn,
  isGenerated,
  pathAllowed,
  termsFromCargoToml,
  termsFromFile,
  termsFromGoMod,
  termsFromMakefile,
  termsFromPackageJson,
  termsFromPyproject,
} from '../src/index.ts';

test('path filter drops env, keys, lockfiles, vendored; keeps keymap.rs', () => {
  assert.equal(pathAllowed('src/keymap.rs'), true);
  assert.equal(pathAllowed('.env'), false);
  assert.equal(pathAllowed('.env.local'), false);
  assert.equal(pathAllowed('secrets.pem'), false);
  assert.equal(pathAllowed('tls.key'), false);
  assert.equal(pathAllowed('secret-token.txt'), false);
  assert.equal(pathAllowed('credentials.json'), false);
  assert.equal(pathAllowed('package-lock.json'), false);
  assert.equal(pathAllowed('Cargo.lock'), false);
  assert.equal(pathAllowed('node_modules/x/index.js'), false);
  assert.equal(pathAllowed('vendor/foo.rs'), false);
  assert.equal(pathAllowed('target/debug/foo'), false);
});

test('lexer skips comments and strings; keeps whole identifiers only', () => {
  const ids = identifiersIn(`
    // teh should not appear
    const ser = "ratatui secret-value";
    /* adn */
    fn OutboxWorker() { let x = 'teh'; }
  `);
  assert.ok(ids.includes('ser'));
  assert.ok(ids.includes('outboxworker'));
  assert.equal(ids.includes('teh'), false);
  assert.equal(ids.includes('ratatui'), false);
  assert.equal(ids.includes('adn'), false);
  // Fragments of OutboxWorker are not emitted (whole-identifier rule).
  assert.equal(ids.includes('outbox'), false);
  assert.equal(ids.includes('worker'), false);
});

test('generated header is skipped', () => {
  assert.equal(isGenerated('// Code generated by protoc. DO NOT EDIT.\nfn foo() {}'), true);
  assert.equal(isGenerated('fn foo() {}'), false);
});

test('manifests yield package and dependency names', () => {
  assert.ok(termsFromPackageJson('{"name":"ratatui","dependencies":{"ser":"1"}}').includes('ratatui'));
  assert.ok(termsFromPackageJson('{"name":"ratatui","dependencies":{"ser":"1"}}').includes('ser'));
  assert.ok(termsFromCargoToml('[package]\nname = "codex"\n[dependencies]\nratatui = "0.1"').includes('ratatui'));
  assert.ok(termsFromPyproject('[project]\nname = "pi"\ndependencies = ["ratatui"]').includes('ratatui'));
  assert.ok(termsFromGoMod('module github.com/user/pi\nrequire github.com/foo/ratatui v1.0.0').includes('ratatui'));
  assert.ok(termsFromMakefile('build:\n\techo x\n').includes('build'));
});

test('string literals are not tokens of a source file', () => {
  const { tokens } = termsFromFile('src/lib.rs', 'const X: &str = "API_KEY=sk-live-example";\nfn ratatui() {}');
  assert.ok(tokens.includes('ratatui'));
  assert.equal(
    tokens.some((t) => t.includes('sk') || t.includes('api')),
    false,
  );
});

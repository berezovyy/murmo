// Builds the English language pack from the pinned inputs, offline and
// deterministically (docs/plan/12, "Build"):
//
//   generated base (generate.ts) + reviewed authored list (authored.ts)
//   + inline overrides  →  typos.bin, provenance.csv, case-policy.json,
//                          NOTICE, licenses/, manifest.json
//
// A later source never replaces an earlier mapping: an authored line or an
// override that maps an existing key to a different word stops the build.

import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import {
  CASE_POLICY_FORMAT,
  encodeTable,
  type LanguagePackManifest,
  mapTable,
  PACK_KIND,
  PROVENANCE_FORMAT,
  parseCasePolicy,
  type SourcePin,
  TABLE_FORMAT,
  type ValidationReceipt,
  validatePack,
} from '@murmo/lang';
import { type AuthoredEntry, type AuthoredResult, reviewAuthored } from './authored.ts';
import { type BaseResult, generateBase } from './generate.ts';
import { defaultInputsDir, type Inputs, loadInputs, sha256 } from './inputs.ts';
import { buildLexicon } from './lexicon.ts';
import { DATA_POLICY, PACK_FILES, STRICT } from './policy.ts';
import { csvLine, PROVENANCE_COLUMNS, type ProvenanceRow } from './provenance.ts';

/** Bumped when the pipeline's output for the same inputs changes. */
export const PIPELINE_VERSION = '1';
export class BuildError extends Error {
  constructor(message: string) {
    super(message);
    this.name = 'BuildError';
  }
}

export interface TableSummary {
  readonly entries: number;
  readonly bytes: number;
  readonly sha256: string;
}

export interface BuildReport {
  readonly outDir: string;
  readonly base: TableSummary & { readonly result: Omit<BaseResult, 'entries'> };
  readonly authored: Omit<AuthoredResult, 'kept'> & { readonly kept: number; readonly newKeys: number };
  /** Base plus authored list: round 8's combined table. */
  readonly combined: TableSummary;
  readonly overrides: number;
  /** The shipped table. */
  readonly table: TableSummary;
  readonly provenanceRows: number;
  readonly receipt: ValidationReceipt;
}

const summarize = (bytes: Uint8Array, entries: number): TableSummary => ({
  entries,
  bytes: bytes.length,
  sha256: sha256(bytes),
});

const NOTICE = (scowlVersion: string) => `Murmo English typo data (language pack "en", policy ${DATA_POLICY})

The table holds two kinds of entries:

- Keyboard slips generated by Murmo's own code from SCOWL ${scowlVersion} word
  lists (Copyright Kevin Atkinson and the authors named in
  licenses/SCOWL-Copyright). The word lists were modified: Murmo generated
  misspellings of them and kept only some. Retain licenses/SCOWL-Copyright
  verbatim, including every component notice.
- Common typos written by the Murmo project, and two round-13 overrides
  (wich, i). Original Murmo work.

No pair comes from a public typo list (typos, codespell, misspell, Wikipedia);
those lists were used only to evaluate, never as input. The system dictionary
(web2) and project vocabularies only removed candidates; none of their words
are shipped.

provenance.csv names, for every entry, the SCOWL file and line of its
correction or the line of the hand-written list it came from.

case-policy.json is part of the data: its keys (teh, adn, thier) must be
corrected only when typed in lowercase, so the names Teh and Thier and the
abbreviation ADN stay as typed. Project and user vocabulary always win.

The correction rate is not zero (about 1 wrong fix per 1,800 changed words on
round 8's held-out slips), which is why automatic correction is opt-in.
`;

/** Builds into `outDir` (created if needed) and validates the result. */
export function buildPack(outDir: string, inputsDir = defaultInputsDir): BuildReport {
  const inputs = loadInputs(inputsDir);
  const lexicon = buildLexicon(inputs);
  const casePolicy = parseCasePolicy(JSON.parse(Buffer.from(inputs.casePolicyBytes).toString('utf8')));

  const base = generateBase(lexicon, new Set(Object.keys(inputs.baseVetoes)), STRICT);
  const baseBytes = encodeTable(base.entries.map((e) => [e.key, e.value]));

  const authored = reviewAuthored(inputs.authored, inputs.authoredReview, lexicon, casePolicy.lowercaseOnly);
  const merged = new Map<string, string>(base.entries.map((e) => [e.key, e.value]));
  const rows: ProvenanceRow[] = base.entries.map((e) => ({
    key: e.key,
    value: e.value,
    origin: 'scowl-generated',
    category: e.slip,
    file: `${inputs.scowlRoot}/final/${e.target.file}`,
    line: e.target.line,
    level: e.target.level,
    review: '',
  }));
  const newKeys = mergeAuthored(merged, rows, authored.kept);
  const combinedBytes = encodeTable(merged);
  const combined = summarize(combinedBytes, merged.size);

  const overrides = addOverrides(merged, rows, inputs.inlineOverrides);

  const tableBytes = encodeTable(merged);
  // The case policy must name keys this table has (parseCasePolicy checks against it).
  parseCasePolicy(JSON.parse(Buffer.from(inputs.casePolicyBytes).toString('utf8')), mapTable(tableBytes));
  rows.sort((a, b) => (a.key < b.key ? -1 : a.key > b.key ? 1 : 0));
  const csv = `${[PROVENANCE_COLUMNS.join(','), ...rows.map(csvLine)].join('\n')}\n`;

  const files: Record<string, Uint8Array> = {
    [PACK_FILES.table]: tableBytes,
    [PACK_FILES.casePolicy]: inputs.casePolicyBytes,
    [PACK_FILES.provenance]: Buffer.from(csv, 'utf8'),
    [PACK_FILES.notice]: Buffer.from(NOTICE(scowlVersionOf(inputs)), 'utf8'),
    [PACK_FILES.scowlCopyright]: inputs.scowlCopyright,
  };
  const ref = (file: string) => ({
    file,
    sha256: sha256(files[file] as Uint8Array),
    bytes: (files[file] as Uint8Array).length,
  });
  const manifest: LanguagePackManifest = {
    kind: PACK_KIND,
    language: 'en',
    policy: DATA_POLICY,
    table: { ...ref(PACK_FILES.table), format: TABLE_FORMAT, entries: merged.size },
    casePolicy: { ...ref(PACK_FILES.casePolicy), format: CASE_POLICY_FORMAT },
    provenance: { ...ref(PACK_FILES.provenance), format: PROVENANCE_FORMAT, rows: rows.length },
    notice: ref(PACK_FILES.notice),
    licenses: [
      {
        ...ref(PACK_FILES.scowlCopyright),
        covers: `SCOWL ${scowlVersionOf(inputs)} word lists and their component lists`,
      },
    ],
    sources: inputs.pins.map(
      (p): SourcePin => ({
        name: p.name,
        version: p.version,
        sha256: p.sha256,
        license: p.license,
        role: p.role,
        ...(p.url === undefined ? {} : { url: p.url }),
      }),
    ),
    build: { tool: '@murmo/lang-en', version: PIPELINE_VERSION },
  };
  const manifestBytes = Buffer.from(`${JSON.stringify(manifest, null, 2)}\n`, 'utf8');

  for (const [file, bytes] of Object.entries({ ...files, [PACK_FILES.manifest]: manifestBytes })) {
    const path = join(outDir, file);
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, bytes);
  }
  // Full validation of what was written: the same check `murmo setup` runs.
  const receipt = validatePack(manifestBytes, (file) => files[file], sha256);

  const { entries: _entries, ...baseResult } = base;
  const { kept, ...authoredRest } = authored;
  return {
    outDir,
    base: { ...summarize(baseBytes, base.entries.length), result: baseResult },
    authored: { ...authoredRest, kept: kept.length, newKeys },
    combined,
    overrides,
    table: summarize(tableBytes, merged.size),
    provenanceRows: rows.length,
    receipt,
  };
}

/**
 * Step 4: the authored list joins as deliberate exceptions. A key the base
 * already maps to the same word gets a second provenance row; to a different
 * word, the build stops (base mappings are never replaced silently).
 * Returns the number of new keys.
 */
export function mergeAuthored(
  merged: Map<string, string>,
  rows: ProvenanceRow[],
  kept: readonly AuthoredEntry[],
): number {
  let newKeys = 0;
  for (const e of kept) {
    const existing = merged.get(e.key);
    if (existing !== undefined && existing !== e.value) {
      throw new BuildError(
        `authored.txt line ${e.line} maps "${e.key}" to "${e.value}", but the generated base maps it to "${existing}"; ` +
          'veto the base key in base-vetoes.json or reject the line in authored-review.json',
      );
    }
    if (existing === undefined) newKeys++;
    merged.set(e.key, e.value);
    rows.push({
      key: e.key,
      value: e.value,
      origin: 'authored',
      category: e.category,
      file: 'authored.txt',
      line: e.line,
      level: '',
      review: e.review,
    });
  }
  return newKeys;
}

/** Step 5: inline overrides (`typo correction category` per line) may only add keys. Returns how many. */
export function addOverrides(merged: Map<string, string>, rows: ProvenanceRow[], lines: readonly string[]): number {
  let overrides = 0;
  lines.forEach((text, i) => {
    const [key, value, category, ...rest] = text.trim().split(/\s+/);
    if (!key || !value || !category || rest.length) {
      throw new BuildError(`inline-overrides.txt line ${i + 1}: expected \`typo correction category\``);
    }
    const existing = merged.get(key);
    if (existing !== undefined) {
      throw new BuildError(`inline-overrides.txt line ${i + 1}: "${key}" is already mapped to "${existing}"`);
    }
    merged.set(key, value);
    rows.push({
      key,
      value,
      origin: 'inline-override',
      category,
      file: 'inline-overrides.txt',
      line: i + 1,
      level: '',
      review: '',
    });
    overrides++;
  });
  return overrides;
}

function scowlVersionOf(inputs: Inputs): string {
  return inputs.scowlRoot.slice('scowl-'.length);
}
